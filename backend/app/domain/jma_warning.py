# サイクリングに関連する種別への絞り込み（改善計画T205完了条件(2)(3)）。
# 大雨・洪水・暴風/強風・波浪・大雪・雷は着手時のユーザー要望に明記の系統。土砂災害は
# 山間部ロングライドの通行可否に直結するため実装時に追加した（レビュー時の判断）。
# 以下は意図的に対象外（「対象外の種別は表示しない」という完了条件の「津波」と同種の
# 除外で、いずれも別タスクとして扱う予定があるか、道路上のサイクリングとの関連が薄い）:
# - 霜(24)・着氷(25)・着雪(26)・なだれ(22)・低温(23): T206（積雪・凍結、トリガー:
#   冬季前）で改めて扱う。ここに含めると「路面凍結」という同一テーマの警告が2つの
#   別タスク・別実装に分散してしまう。
# - 濃霧(20): T208（視程・霧、調査のみ）で改めて扱う。
# - 高潮(08/19/38/48)・乾燥(21)・その他の注意報(27): 道路走行への直接的な関連が薄い。
CYCLING_RELEVANT_WARNING_CODES: frozenset[str] = frozenset(
    {
        "02", "03", "04", "05", "06", "07", "09",
        "10", "12", "13", "14", "15", "16", "18", "29",
        "32", "33", "35", "36", "37", "39",
        "43", "49",
    }
)

# 警報・注意報が「現在発表中」であることを示すstatus値。「解除」（直前まで出ていたが
# 取り下げられた）と「発表警報・注意報はなし」（元々何も出ていない、code自体を持たない）
# はどちらも現在アクティブではないため対象外。
ACTIVE_STATUSES = frozenset({"発表", "継続"})


def warning_level(code: str) -> str:
    """コードから3段階の警戒レベル（バッジの色分けに使う）を導出する。

    レベルを別テーブルとして二重管理せず、名称文字列（「特別警報」「警報」を含むか）
    から導出する（設計原則2）。"""
    name = WARNING_CODE_NAMES.get(code, "")
    if "特別警報" in name:
        return "emergency_warning"
    if "警報" in name:
        return "warning"
    return "advisory"


class ActiveWarning(BaseModel):
    code: str
    name: str
    level: str
    additions: list[str]


def extract_active_warnings(kinds: list[dict]) -> list[ActiveWarning]:
    """JMA r8警報JSONの1地域ぶんの`kinds`配列から、サイクリングに関連し現在発表中の
    警報・注意報だけを取り出す。

    `kinds`の要素は`{"code": "14", "status": "発表", "additions": [...]}`（発表中）、
    または警報が何も無い地域の`{"status": "発表警報・注意報はなし"}`（codeキー自体が
    無い）のいずれか。"""
    result: list[ActiveWarning] = []
    for kind in kinds:
        code = kind.get("code")
        status = kind.get("status")
        if code is None or status not in ACTIVE_STATUSES:
            continue
        if code not in CYCLING_RELEVANT_WARNING_CODES:
            continue
        result.append(
            ActiveWarning(
                code=code,
                name=WARNING_CODE_NAMES.get(code, code),
                level=warning_level(code),
                additions=kind.get("additions", []),
            )
        )
    return result
